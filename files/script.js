// ===== Форматирование цены =====
const priceFormatter = new Intl.NumberFormat("ru-RU");
function formatPrice(price) {
  if (typeof price !== "number" || !isFinite(price) || price <= 0) return null;
  return priceFormatter.format(price) + " сум";
}

// ===== Вспомогательные функции =====
function el(tag, className, text) {
  const node = document.createElement(tag);
  if (className) node.className = className;
  if (text !== undefined) node.textContent = text;
  return node;
}

function norm(s) { return String(s || "").toLowerCase().replace(/ё/g, "е").trim(); }

const state = { cat: "all", query: "" };
const $menu = document.getElementById("menu");
const $cats = document.getElementById("cats");
const $search = document.getElementById("search");
const $clear = document.getElementById("clear");

// ===== Карточка блюда =====
function buildCard(item, icon) {
  const card = el("article", "card");
  const imgBox = el("div", "img");

  const ph = el("div", "placeholder");
  ph.appendChild(el("span", "ico", icon));
  ph.appendChild(el("span", "wg", "WG"));
  imgBox.appendChild(ph);

  if (item.image) {
    const img = document.createElement("img");
    img.src = IMAGE_DIR + item.image;
    img.alt = item.name;
    img.loading = "lazy";
    img.onerror = function () { img.remove(); };   // нет файла — остаётся placeholder
    imgBox.appendChild(img);
  }
  card.appendChild(imgBox);

  const body = el("div", "body");
  body.appendChild(el("h3", "", item.name));
  if (item.description) body.appendChild(el("p", "", item.description));

  const formatted = formatPrice(item.price);
  const price = el("div", formatted ? "price" : "price unknown");
  price.textContent = formatted ? formatted.replace(" сум", "") : "Цена уточняется";
  if (formatted) price.appendChild(el("small", "", "сум"));
  body.appendChild(price);

  card.appendChild(body);
  return card;
}

// ===== Отрисовка меню =====
function render() {
  const q = norm(state.query);
  $menu.textContent = "";
  let found = 0;

  MENU.forEach(function (cat) {
    if (state.cat !== "all" && state.cat !== cat.id) return;
    const items = cat.items.filter(function (it) { return !q || norm(it.name).includes(q); });
    if (!items.length) return;

    const section = el("section", "section");
    section.id = "cat-" + cat.id;
    section.appendChild(el("h2", "", cat.title));
    const grid = el("div", "grid");
    items.forEach(function (it) { grid.appendChild(buildCard(it, cat.icon)); });
    section.appendChild(grid);
    $menu.appendChild(section);
    found += items.length;
  });

  if (!found) $menu.appendChild(el("div", "empty", "Блюда не найдены"));
}

// ===== Кнопки категорий =====
function buildCategories() {
  const list = [{ id: "all", title: "Всё меню" }].concat(MENU);
  list.forEach(function (cat) {
    const btn = el("button", "chip" + (cat.id === state.cat ? " active" : ""), cat.title);
    btn.type = "button";
    btn.dataset.id = cat.id;
    btn.addEventListener("click", function () {
      state.cat = cat.id;
      $cats.querySelectorAll(".chip").forEach(function (c) { c.classList.toggle("active", c === btn); });
      btn.scrollIntoView({ behavior: "smooth", inline: "center", block: "nearest" });
      render();
      window.scrollTo({ top: 0, behavior: "smooth" });
    });
    $cats.appendChild(btn);
  });
}

// ===== Поиск =====
$search.addEventListener("input", function () {
  state.query = $search.value;
  $clear.hidden = !$search.value;
  render();
});
$clear.addEventListener("click", function () {
  $search.value = "";
  state.query = "";
  $clear.hidden = true;
  render();
  $search.focus();
});

// ===== Запуск =====
buildCategories();
render();
